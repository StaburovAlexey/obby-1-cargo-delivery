import assert from 'node:assert/strict';
import fs from 'node:fs';
const html=fs.readFileSync(new URL('../dist/index.html',import.meta.url),'utf8');
const settings=html.slice(html.indexOf('<div id="settings-menu"'),html.indexOf('<div id="music-menu"'));
for(const id of ['settings-how-to-play','settings-icon-guide','settings-jump-play','settings-jump-icons','settings-jump-credits'])assert.ok(!settings.includes(`id="${id}"`));
for(const id of ['settings-volume','settings-language','settings-credits'])assert.ok(settings.includes(`id="${id}"`));
assert.ok(settings.indexOf('id="settings-credits"')>settings.indexOf('id="settings-language"'));
assert.ok(!settings.includes('id="settings-music"'));
assert.ok(settings.includes('CC BY 4.0'));
assert.equal(new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1])).size,[...html.matchAll(/\bid="/g)].length);
console.log('PASS settings: help and jump navigation removed; controls, music and bottom credits retained.');
